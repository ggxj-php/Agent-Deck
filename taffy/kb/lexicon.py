def expand(text):
    """找出查询里的术语，返回要额外补进检索词表的同义词。

    中文术语用**子串命中**来找，不依赖分词结果——分词可能把「二叉搜索树」切成
    「二叉 / 搜索 / 树」，逐词查表就漏了。命中多个时丢掉被更长术语包含的那些，
    免得「树」这种短词把一批无关的词带进来。
    """
    if not text:
        return []

    matched = sorted((cn for cn in TERMS if len(cn) > 1 and cn in text), key=len, reverse=True)
    kept = []
    for cn in matched:
        if not any(cn in longer for longer in kept):
            kept.append(cn)

    extra = []
    for cn in kept:
        extra.extend(TERMS[cn])  # 中文 -> 英文词

    for word in re.findall(r"[A-Za-z][A-Za-z0-9+#.]*", text):
        for cn in _REVERSE.get(word.lower(), ()):
            extra.extend(_segment(cn))  # 英文 -> 中文词

    seen = set()
    result = []
    for token in extra:
        if token not in seen:
            seen.add(token)
            result.append(token)
    return result